/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
#include "qlib_platform.h"

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                        LOCAL FUNCTION PROTOTYPES                                        */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
static uint64_t PLAT_GetNONCE_SW_L(void);

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                                           INTERFACE FUNCTIONS                                           */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/

uint64_t PLAT_GetNONCE(void)
{
    uint64_t nonce = 0;
    nonce = PLAT_GetNONCE_SW_L();
    return nonce;
}

/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/
/*                  GetNONCE SW IMPLEMENTATION, IRRELEVANT IF HW IMPLEMENTATION SUPPLIED                   */
/*---------------------------------------------------------------------------------------------------------*/
/*---------------------------------------------------------------------------------------------------------*/

static uint64_t PLAT_GetNONCE_SW_L(void)
{
    /*-----------------------------------------------------------------------------------------------------*/
    /* We use here 64bit XORSHIFT algorithm for PRNG                                                       */
    /*-----------------------------------------------------------------------------------------------------*/
    static uint64_t x = 0x500DF00D;
    x ^= x << 13;
    x ^= x >> 7;
    x ^= x << 17;
    return x;
}

